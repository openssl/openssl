# Build-time generator for crypto/ec/ec_curves.inc.
# Reads crypto/ec/ec_curves.conf (config-target style data file) and
# configdata.pm (for disabled() / %disabled), emits a C include file with
# the curve structs, the static OSSL_FN constants and BIGNUM views, and
# the curve_list[] tables for the enabled curves.

use strict;
use warnings;
use FindBin;
use lib '.';                    # for configdata.pm
use configdata;

# Helper for the enabled coderefs in ec_curves.conf
sub disabled {
    my ($feature) = @_;
    return exists $disabled{$feature} && $disabled{$feature};
}

# Load the curve data; the file's last expression is a list of
# name => record pairs in curve_list order
my @pairs = do "$FindBin::Bin/ec_curves.conf";
die "Cannot load ec_curves.conf: $@" if $@;
die "Cannot load ec_curves.conf: $!" unless @pairs;

my (@order, %curves);
while (@pairs) {
    my ($name, $record) = splice @pairs, 0, 2;
    push @order, $name;
    $curves{$name} = $record;
}

# ------------------------------------------------------------------
# Helpers
# ------------------------------------------------------------------

# Sanitize a name to a C identifier (same as objects.pl)
sub sanitize {
    my ($name) = @_;
    $name =~ s/-/_/g;
    $name =~ s/\./_/g;
    return $name;
}

# Resolve a record through an alias; returns (canonical_name, record)
sub resolve {
    my ($name) = @_;
    my $c = $curves{$name};
    if (exists $c->{alias_of}) {
        return ($c->{alias_of}, $curves{$c->{alias_of}});
    }
    return ($name, $c);
}

sub is_enabled {
    my ($name) = @_;
    my ($cname, $c) = resolve($name);
    if (exists $c->{enabled} && ref $c->{enabled} eq 'CODE') {
        return $c->{enabled}->();
    }
    return 1;
}

# Convert big-endian hex string to little-endian limb list
sub hex_to_limbs {
    my ($hex) = @_;
    # Left-pad to whole 4-byte words; within each word the bytes are
    # big-endian.
    $hex = '0' x ((8 - length($hex) % 8) % 8) . $hex;
    # Split into 4-byte words, then reverse to little-endian limb order.
    my @words = reverse unpack '(H8)*', pack 'H*', $hex;
    # Emit OSSL_FN_ULONG64_C pairs of words; a trailing odd word becomes a
    # single OSSL_FN_ULONG_C.  This matches OSSL_FN_LIMBS_N() on both 32-
    # and 64-bit platforms.
    my @limbs;
    while (@words) {
        my $lo = shift @words;
        if (@words) {
            my $hi = shift @words;
            push @limbs, "OSSL_FN_ULONG64_C(0x$hi, 0x$lo)";
        } else {
            push @limbs, "OSSL_FN_ULONG_C(0x$lo)";
        }
    }
    return @limbs;
}

# Significant bits of a value given as a hex string; the BIGNUM top field
# (in BN_ULONG units) follows from OSSL_FN_LIMBS_N of this count
sub sig_bits {
    my ($hex) = @_;
    $hex =~ s/^0+//;   # strip leading zeros
    return 0 if $hex eq '';
    my $top = hex(substr $hex, 0, 1);
    my $bits_in_top = $top >= 8 ? 4 : $top >= 4 ? 3 : $top >= 2 ? 2 : 1;
    return 4 * (length($hex) - 1) + $bits_in_top;
}

# Escape a string for embedding in a C string literal
sub c_string {
    my ($s) = @_;
    $s =~ s/\\/\\\\/g;
    $s =~ s/"/\\"/g;
    $s =~ s/\n/\\n/g;
    $s =~ s/\t/\\t/g;
    return $s;
}

# Emit a byte array initializer, 12 bytes per line
sub emit_bytes {
    my ($hex) = @_;
    die "odd number of hex digits\n" if length($hex) % 2;
    my @bytes = unpack '(H2)*', pack 'H*', $hex;
    my @lines;
    while (@bytes) {
        my @chunk = splice @bytes, 0, 12;
        push @lines, '        ' . join(', ', map { "0x$_" } @chunk);
    }
    return join(",\n", @lines);
}

# ------------------------------------------------------------------
# Generate
# ------------------------------------------------------------------

my @enabled = grep { is_enabled($_) } @order;
my @canonical = grep { !exists $curves{$_}{alias_of} } @enabled;

my $output = <<'HEADER';
/*
