 * the same name with the LIBX509PMI_ prefix, so that libx509pmi shares no
 * symbol with libcrypto's copy of the same sources.  The macros are only
 * active when OSSL_LIBX509PMI_NAMES is defined, which the libx509pmi entry
 * headers do.
