# Emit include/libx509pmi/names.h on standard output: one object-like
# macro per symbol the PMI sources define with external linkage, renaming
# it to the same name with the LIBX509PMI_ prefix.  The macros are only
# active when OSSL_LIBX509PMI_NAMES is defined.
#
# With --filter-num FILE, rewrite the ordinals file FILE instead, keeping
# only the symbols the PMI sources define.  The PMI declarations share
# <openssl/x509v3.h> with the rest of the X.509v3 API, so mknum.pl run on
# that header lists symbols libx509pmi does not have.
#
# The symbols are collected from the sources: the ASN.1 items and functions
# the templates define, which the ASN.1 macros paste together from the type
# name, the PEM functions, the extension methods, the ossl_x509pmi_*()
# functions and every other function defined at file scope.  A symbol
# missed here keeps the name libcrypto's copy of the same source uses,
# which shows up as a duplicate definition when both libraries are linked
# statically.

use strict;
use warnings;
use FindBin;
use Getopt::Long;

my $filter_num;
GetOptions('filter-num=s' => \$filter_num) or die "bad options\n";
my $top = $ARGV[0] // "$FindBin::Bin/..";
my %names;

foreach my $src (glob("$top/x509pmi/*.c")) {
    open my $fh, '<', $src or die "$src: $!\n";
    my $prev = '';
    while (<$fh>) {
        chomp;
        # Every template names its type in the _END macro, wherever the
        # formatting has put it.  Naming a static item too is harmless.
        $names{"$1_it"} = 1
            while /ASN1_(?:NDEF_)?(?:SEQUENCE|CHOICE|ITEM_TEMPLATE)_END(?:_cb)?\(([A-Za-z0-9_]+)/g;

        if (/^IMPLEMENT_ASN1_([A-Z_]+)\(([A-Za-z0-9_]+)/) {
            my ($what, $type) = ($1, $2);
            $names{"${type}_it"} = 1;
            $names{"${type}_new"} = $names{"${type}_free"} = 1
                unless $what eq 'ENCODE_FUNCTIONS';
            $names{"d2i_$type"} = $names{"i2d_$type"} = 1
                unless $what eq 'ALLOC_FUNCTIONS';
            $names{"${type}_dup"} = 1 if $what eq 'DUP_FUNCTION';
            next;
        }

        if (/^IMPLEMENT_PEM_rw\(([A-Za-z0-9_]+)/) {
            $names{"PEM_${_}_$1"} = 1
                foreach qw(read write read_bio write_bio);
            next;
        }

        $names{$1} = 1 if /^const X509V3_EXT_METHOD ([A-Za-z0-9_]+)/;

        # Function definitions at file scope.  Only the external ones can
        # collide, and only those may be renamed: renaming something the
        # sources merely call would look for it under the wrong name.
        next if /^static\b/;
        # A type macro such as "const STACK_OF(X509) *" is not a name
        s/\b(?:STACK_OF|LHASH_OF)\s*\([^()]*\)/TYPE/g;
        $names{$1} = 1
            if /^[A-Za-z_][A-Za-z0-9_ ]*[ *]([A-Za-z_][A-Za-z0-9_]*)\(/;
        # The same, with the return type on the line before
        $names{$1} = 1
            if $prev =~ /^[A-Za-z_][A-Za-z0-9_ ]*[ *]$/
               && /^([A-Za-z_][A-Za-z0-9_]*)\(/;
    } continue {
        $prev = $_;
    }
    close $fh;
}

if (defined $filter_num) {
    open my $in, '<', $filter_num or die "$filter_num: $!\n";
    my @keep = grep { /^\s*#/ || /^\s*$/ || $names{(split /\s+/)[0]} } <$in>;
    close $in;
    open my $out, '>', $filter_num or die "$filter_num: $!\n";
    print $out @keep;
    close $out;
    exit 0;
}

print <<"_____";
/*
