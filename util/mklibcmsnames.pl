foreach (sort keys %names) {
    printf "#define %-*s LIBCMS_%s\n", 45, $_, $_;
}
print <<"_____";
#endif /* defined(OSSL_LIBCMS_NAMES) */
#endif /* !defined(LIBCMS_NAMES_H) */
