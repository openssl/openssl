 * Generated by util/mklibcmpnames.pl from util/libcmp.num and the CMP and
 * CRMF sources.
 *
 * Renames every symbol those sources define with external linkage to the
 * same name with the LIBCMP_ prefix, so that libcmp shares no symbol with
 * libcrypto's copy of the same sources.  The macros are only active when
 * OSSL_LIBCMP_NAMES is defined, which the libcmp entry headers do.
 *
